"""A markdown wiki generated from the graph alone — no LLM, no network.

``generate_wiki`` writes ``.codegraph/wiki/``: ``index.md`` (counts, languages, every
module grouped by top-level package, non-code nodes such as routes and resources),
``modules/<qname>.md`` for each module (its definitions with signatures and first
docstring lines, imports both ways, callers from other modules, covering tests, and
every other relationship touching the file, whatever its kind), and
``communities/<label>.md`` when an analysis pass stored community membership.

Pages are regenerated wholesale; stale pages from modules that disappeared are
removed, but only ``.md`` files inside the wiki's own sub-directories are touched.
"""

from __future__ import annotations

import re
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

from codegraph.exports import GraphData, load_graph
from codegraph.models import Edge, Node
from codegraph.store import DB_DIRNAME, GraphStore

WIKI_DIRNAME = "wiki"
_CODE_KINDS = frozenset({"module", "class", "function", "method"})
_SHOWN_ELSEWHERE = frozenset({"defines", "imports", "calls", "tests"})


class WikiError(ValueError):
    """A page name that escapes the wiki directory."""


@dataclass(frozen=True, slots=True)
class WikiResult:
    directory: Path
    pages: tuple[str, ...]
    removed: tuple[str, ...]


def wiki_dir(root: Path) -> Path:
    return root / DB_DIRNAME / WIKI_DIRNAME


def page_slug(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", text).strip("_") or "_"


def _first_line(text: str | None) -> str:
    return text.strip().splitlines()[0].strip() if text and text.strip() else ""


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


@dataclass(frozen=True, slots=True)
class WikiIndex:
    """Lookups shared by every page, built once per generation."""

    nodes: dict[str, Node]
    by_path: dict[str, list[Node]]
    module_of_path: dict[str, str]
    out_edges: dict[str, list[Edge]]
    in_edges: dict[str, list[Edge]]


def build_index(data: GraphData) -> WikiIndex:
    nodes = {n.qname: n for n in data.nodes}
    by_path: defaultdict[str, list[Node]] = defaultdict(list)
    for node in data.nodes:
        by_path[node.path].append(node)
    module_of_path = {n.path: n.qname for n in data.nodes if n.kind == "module"}
    out_edges: defaultdict[str, list[Edge]] = defaultdict(list)
    in_edges: defaultdict[str, list[Edge]] = defaultdict(list)
    for edge in data.edges:
        out_edges[edge.src].append(edge)
        in_edges[edge.dst].append(edge)
    return WikiIndex(nodes, dict(by_path), module_of_path, dict(out_edges), dict(in_edges))


def _link(index: WikiIndex, qname: str, prefix: str) -> str:
    node = index.nodes.get(qname)
    module = index.module_of_path.get(node.path) if node else None
    if module is None:
        return f"`{qname}`"
    return f"[`{qname}`]({prefix}modules/{page_slug(module)}.md)"


def render_index(
    root: Path, data: GraphData, index: WikiIndex, grouped: dict[str, dict[str, int]]
) -> str:
    lines = [f"# {root.name} code wiki", "", "Generated by codegraph from the code graph.", ""]
    lines += ["## Counts", "", "| | kind | count |", "| --- | --- | --- |"]
    for section in ("nodes", "edges", "languages"):
        for kind, count in grouped[section].items():
            lines.append(f"| {section} | {kind} | {count} |")
    modules = sorted((n for n in data.nodes if n.kind == "module"), key=lambda n: n.qname)
    packages: defaultdict[str, list[Node]] = defaultdict(list)
    for module in modules:
        packages[module.qname.split(".")[0]].append(module)
    lines += ["", "## Modules", ""]
    for package, members in sorted(packages.items()):
        lines += [f"### {package}", ""]
        for module in members:
            summary = _first_line(module.docstring)
            tail = f" — {summary}" if summary else ""
            lines.append(f"- {_link(index, module.qname, '')} (`{module.path}`){tail}")
        lines.append("")
    others: defaultdict[str, list[Node]] = defaultdict(list)
    for node in data.nodes:
        if node.kind not in _CODE_KINDS:
            others[node.kind].append(node)
    for kind, members in sorted(others.items()):
        lines += [f"## {kind.capitalize()} nodes", ""]
        for node in sorted(members, key=lambda n: n.qname):
            lines.append(f"- `{node.qname}` (`{node.path}:{node.line_start}`)")
        lines.append("")
    if data.communities:
        sizes: defaultdict[str, int] = defaultdict(int)
        for label in data.communities.values():
            sizes[label] += 1
        lines += ["## Communities", ""]
        for label, size in sorted(sizes.items(), key=lambda item: (-item[1], item[0])):
            lines.append(f"- [{label}](communities/{page_slug(label)}.md) — {size} members")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_module(module: Node, data: GraphData, index: WikiIndex) -> str:
    members = sorted(
        (n for n in index.by_path.get(module.path, []) if n.qname != module.qname),
        key=lambda n: n.line_start,
    )
    own = {module.qname, *(n.qname for n in members)}
    lines = [f"# {module.qname}", "", f"`{module.path}` · {module.language}", ""]
    if module.docstring:
        lines += [module.docstring.strip(), ""]
    community = data.communities.get(module.qname)
    if community:
        lines += [f"Community: [{community}](../communities/{page_slug(community)}.md)", ""]

    if members:
        lines += ["## Definitions", ""]
        for node in members:
            lines += [f"### {node.qname}", ""]
            lines.append(f"{node.kind} · lines {node.line_start}-{node.line_end}")
            if node.signature:
                lines += ["", "```", node.signature, "```"]
            summary = _first_line(node.docstring)
            if summary:
                lines += ["", summary]
            callers = sorted(
                {e.src for e in index.in_edges.get(node.qname, []) if e.kind == "calls"} - own
            )
            tests = sorted({e.src for e in index.in_edges.get(node.qname, []) if e.kind == "tests"})
            if callers:
                lines += ["", "Called from: " + ", ".join(_link(index, c, "../") for c in callers)]
            if tests:
                lines += ["", "Tested by: " + ", ".join(_link(index, t, "../") for t in tests)]
            lines.append("")

    imports = sorted({e.dst for e in index.out_edges.get(module.qname, []) if e.kind == "imports"})
    importers = sorted(
        {e.src for q in own for e in index.in_edges.get(q, []) if e.kind == "imports"} - own
    )
    if imports:
        lines += ["## Imports", ""] + [f"- {_link(index, q, '../')}" for q in imports] + [""]
    if importers:
        lines += ["## Imported by", ""] + [f"- {_link(index, q, '../')}" for q in importers] + [""]

    related: list[str] = []
    for qname in sorted(own):
        for edge in index.out_edges.get(qname, []):
            if edge.kind not in _SHOWN_ELSEWHERE:
                related.append(_relation(index, edge))
        for edge in index.in_edges.get(qname, []):
            if edge.kind not in _SHOWN_ELSEWHERE and edge.src not in own:
                related.append(_relation(index, edge))
    if related:
        lines += ["## Other relationships", ""] + sorted(set(related)) + [""]
    return "\n".join(lines).rstrip() + "\n"


def _relation(index: WikiIndex, edge: Edge) -> str:
    detail = f" ({edge.detail})" if edge.detail else ""
    resolved = "" if edge.resolved else " — unresolved"
    return (
        f"- {_link(index, edge.src, '../')} **{edge.kind}** "
        f"{_link(index, edge.dst, '../')}{detail}{resolved}"
    )


def render_community(label: str, data: GraphData, index: WikiIndex) -> str:
    members = sorted(q for q, c in data.communities.items() if c == label and q in index.nodes)
    by_module: defaultdict[str, list[str]] = defaultdict(list)
    for qname in members:
        node = index.nodes[qname]
        by_module[index.module_of_path.get(node.path, node.path)].append(qname)
    lines = [f"# Community {label}", "", f"{len(members)} members.", ""]
    for module, qnames in sorted(by_module.items()):
        lines += [f"## {module}", ""] + [f"- {_link(index, q, '../')}" for q in qnames] + [""]
    outward: defaultdict[str, int] = defaultdict(int)
    member_set = set(members)
    for qname in members:
        for edge in index.out_edges.get(qname, []):
            other = data.communities.get(edge.dst)
            if edge.dst not in member_set and other is not None and other != label:
                outward[other] += 1
    if outward:
        lines += ["## Depends on", ""]
        for other, count in sorted(outward.items(), key=lambda item: (-item[1], item[0])):
            lines.append(f"- [{other}]({page_slug(other)}.md) — {count} edges")
    return "\n".join(lines).rstrip() + "\n"


def generate_wiki(root: Path, store: GraphStore, out_dir: Path | None = None) -> WikiResult:
    directory = out_dir if out_dir is not None else wiki_dir(root)
    data = load_graph(store)
    index = build_index(data)
    pages: dict[str, str] = {"index.md": render_index(root, data, index, store.counts_by_kind())}
    for module in (n for n in data.nodes if n.kind == "module"):
        pages[f"modules/{page_slug(module.qname)}.md"] = render_module(module, data, index)
    for label in sorted(set(data.communities.values())):
        pages[f"communities/{page_slug(label)}.md"] = render_community(label, data, index)

    for rel, text in pages.items():
        target = directory / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    removed: list[str] = []
    for sub in ("modules", "communities"):
        folder = directory / sub
        if not folder.is_dir():
            continue
        for stale in sorted(folder.glob("*.md")):
            rel = f"{sub}/{stale.name}"
            if rel not in pages:
                stale.unlink()
                removed.append(rel)
    return WikiResult(directory=directory, pages=tuple(sorted(pages)), removed=tuple(removed))


def read_wiki_page(root: Path, page: str, out_dir: Path | None = None) -> str | None:
    """Read ``index``, ``modules/<qname>``, a bare module qname, or a community label."""
    directory = (out_dir if out_dir is not None else wiki_dir(root)).resolve()
    name = page.strip().removesuffix(".md") or "index"
    candidates = [name, f"modules/{page_slug(name)}", f"communities/{page_slug(name)}"]
    for candidate in candidates:
        path = (directory / f"{candidate}.md").resolve()
        if not path.is_relative_to(directory):
            raise WikiError(f"page {page!r} is outside the wiki")
        if path.is_file():
            return path.read_text(encoding="utf-8")
    return None


def list_wiki_pages(root: Path, out_dir: Path | None = None) -> list[str]:
    directory = out_dir if out_dir is not None else wiki_dir(root)
    if not directory.is_dir():
        return []
    return sorted(p.relative_to(directory).as_posix() for p in directory.rglob("*.md"))


